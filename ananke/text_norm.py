r"""§6 归一化：记忆同一性判据的**唯一**实现（协议 v4 §6 成文）。

为什么这是"理论概念的实现完整性"而非代码卫生
============================================
归一化函数定义的是"什么算同一条记忆"——这是约束场理论里记忆同一性的
操作化判据。它现在是三个消费者的共同依赖：
  - 两级缓存 key（cache.py）
  - §6 分歧集 D 的对齐（divergence_analysis.py）
  - 重放等价性指纹（replay_equiv_test.py）
若这份判据在代码里存在两份拷贝，等于协议条款有两个可独立漂移的实现——
这正是当初 P0-A 三方矛盾（协议/代码/测试各说各话）的同源病灶。
故：此处是唯一来源，其余两处必须 import 本模块，不得复制。

规则：小写化 → 去除所有非字母数字/非空白字符（去标点；unicode 下的单词
字符类覆盖中文）→ 折叠连续空白并去首尾空白。
"""
from __future__ import annotations

import re


def normalize(content: str) -> str:
    """内容归一化键（跨运行同一性判据）。

    两次独立运行里同一条事实会生成不同 UUID，比对必须按内容对齐，
    否则会把同一事实误报为两条分歧。改写容忍度不在 v0.2 范围
    （措辞不同的同事实仍判为两条分歧，已知限制）。
    """
    s = content.lower()
    s = re.sub(r"\s+", " ", s).strip()
    s = re.sub(r"[^\w\s]", "", s)
    return s
